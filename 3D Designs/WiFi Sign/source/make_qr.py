"""Generate the QR module pattern as OpenSCAD data.

Takes the WiFi string as an ARGUMENT rather than storing it, so the network
password never lands in a file that gets committed. The generated .scad file
holds only the black/white module grid - the credentials are recoverable from
it in the same sense they are recoverable from the printed sign, which is the
entire point of the object, but there is no plaintext to grep for.

  pip install segno
  python3 make_qr.py 'WIFI:S:<ssid>;T:WPA;P:<password>;;' > qr_example.scad

wifi_sign.scad reads qr_example.scad, which as supplied encodes a placeholder
network. Overwrite it with your own (and keep your copy out of anything you
publish: it is your password).

Error correction M: 15% recovery, which is the right trade for a printed
surface - high enough to survive a scuff, low enough to keep modules large.
"""

import sys
import segno

if len(sys.argv) < 2:
    sys.exit("usage: make_qr.py '<wifi string>'")

q = segno.make(sys.argv[1], error="m")
rows = [[1 if m else 0 for m in row] for row in q.matrix]
n = len(rows)

print("// GENERATED by make_qr.py - do not edit.")
print(f"// {n}x{n} modules, error correction M, no quiet zone (added in the model).")
print(f"qr_n = {n};")
print("qr = [")
for r in rows:
    print("  [" + ",".join(str(v) for v in r) + "],")
print("];")
