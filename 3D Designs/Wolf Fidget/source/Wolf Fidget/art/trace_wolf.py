"""Turn the wolf reference drawing into flat color regions for the cap inlay.

    .venv/bin/python "Wolf Fidget/art/trace_wolf.py"

Reads wolf_reference.png, writes ../wolf_art.scad (generated - do not edit)
and art/preview_*.png so the regions can be checked by eye.

The drawing is pencil fur on cream paper. A print can't carry strokes, so it
is posterized into four colors that a P1S AMS can hold: gray fur (the cap's
own color), cream fur, black (eye rims, pupils, nose) and amber (irises).
Every threshold below was chosen by looking at the preview, not computed.

Provenance (owner, 2026-11-11): wolf_reference.png was generated by ChatGPT
from the owner's own description. It is not a third-party artist's work, so
the traced face can ship in a release.
"""
import json
import os
import subprocess
import tempfile

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "wolf_reference.png")
OUT = os.path.join(HERE, "..", "wolf_art.scad")

PAPER = np.array([248, 233, 213.0])   # sampled from the corners
GRAY_LUM = 150      # below: gray fur. 125 lost the dark mask, 140 was blotchy
BLACK_LUM = 70      # eye rims and nostrils, on a lightly blurred copy
NOSE_LUM = 120      # the whole nose leather goes black, not gray with holes
TURD = 250          # px^2: specks smaller than ~0.3mm2 at 40mm are dropped

# Hand-placed regions, in reference pixels: amber and black are only allowed
# in the eyes and the nose. Elsewhere the warm fur tones read as amber specks.
EYES = [(440, 640, 66, 50), (760, 640, 66, 50)]
NOSE = (600, 955, 110, 80)

src = Image.open(SRC).convert("RGB")
H, W = src.size[1], src.size[0]
yy, xx = np.mgrid[0:H, 0:W]


def ell(cx, cy, rx, ry):
    return ((xx - cx) / rx) ** 2 + ((yy - cy) / ry) ** 2 <= 1


def channels(blur):
    a = np.asarray(src.filter(ImageFilter.GaussianBlur(blur))).astype(float)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    return r, g, b, 0.3 * r + 0.59 * g + 0.11 * b


def mode(cls, n):
    return np.asarray(Image.fromarray(cls).filter(ImageFilter.ModeFilter(n))).copy()


# Head outline: anything far from the paper color, closed so the gaps between
# fur tufts fill in, then everything not reachable from the corner.
d = np.sqrt(((np.asarray(src).astype(float) - PAPER) ** 2).sum(-1))
m = Image.fromarray(((d > 30) * 255).astype(np.uint8))
m = m.filter(ImageFilter.MaxFilter(25)).filter(ImageFilter.MinFilter(25))
ImageDraw.floodfill(m, (0, 0), 128)
head = np.asarray(m) != 128
# soften the square filter's stair steps
head = np.asarray(Image.fromarray((head * 255).astype(np.uint8))
                  .filter(ImageFilter.GaussianBlur(6))) > 127

r, g, b, lum = channels(9)
cls = np.full(lum.shape, 1, np.uint8)            # 1 cream
cls[lum < GRAY_LUM] = 2                           # 2 gray
cls = mode(cls, 13)
eyes = np.zeros_like(head)
for e in EYES:
    eyes |= ell(*e)
nose = ell(*NOSE)
r, g, b, lum = channels(3)
cls[(lum < BLACK_LUM) & (eyes | nose)] = 3       # 3 black
cls[(r - b > 55) & (r > 95) & (g > 55) & eyes] = 4   # 4 amber
r, g, b, lum = channels(4)
cls[nose & (lum < NOSE_LUM)] = 3
cls[~head] = 0
cls = mode(cls, 7)
cls[~head] = 0

pal = np.array([[30, 40, 70], [240, 228, 205], [110, 110, 115], [15, 15, 15], [249, 140, 54]], np.uint8)
Image.fromarray(pal[cls]).save(os.path.join(HERE, "preview_regions.png"))


def trace(mask):
    """potrace a boolean mask; returns a list of polygons, each a list of rings."""
    with tempfile.TemporaryDirectory() as t:
        pbm = os.path.join(t, "m.pbm")
        Image.fromarray(((~mask) * 255).astype(np.uint8)).convert("1").save(pbm)
        js = os.path.join(t, "m.json")
        subprocess.run(["potrace", "-b", "geojson", "-t", str(TURD), "-a", "1.0",
                        "-O", "0.4", "-o", js, pbm], check=True)
        gj = json.load(open(js))
    polys = []
    for f in gj["features"]:
        geom = f["geometry"]
        rings = geom["coordinates"] if geom["type"] == "Polygon" else [r for p in geom["coordinates"] for r in p]
        polys.append(rings)
    return polys


def scad_module(name, polys):
    """One OpenSCAD polygon per traced path, holes included. Units: reference px,
    y up (potrace's own frame), origin at the image's bottom-left."""
    out = [f"module {name}() union() {{"]
    for rings in polys:
        pts, paths = [], []
        for ring in rings:
            ring = ring[:-1] if ring[0] == ring[-1] else ring
            paths.append(list(range(len(pts), len(pts) + len(ring))))
            pts += [[round(x, 1), round(y, 1)] for x, y in ring]
        out.append(f"  polygon(points={json.dumps(pts)}, paths={json.dumps(paths)});")
    out.append("}")
    return "\n".join(out)


parts = {"wolf_head2d": head, "wolf_cream2d": cls == 1, "wolf_black2d": cls == 3, "wolf_amber2d": cls == 4}
with open(OUT, "w") as f:
    f.write("// generated from art/wolf_reference.png by art/trace_wolf.py - do not edit\n")
    f.write(f"wolf_px_w = {W};\nwolf_px_h = {H};\n")
    xs = np.where(head.any(0))[0]
    ys = np.where(head.any(1))[0]
    # head extent in potrace's frame (y up from the image bottom)
    f.write(f"wolf_box = [[{xs[0]}, {H - 1 - ys[-1]}], [{xs[-1] + 1}, {H - ys[0]}]];\n")
    for name, mask in parts.items():
        f.write(scad_module(name, trace(mask)) + "\n")
print("wrote", os.path.relpath(OUT))
